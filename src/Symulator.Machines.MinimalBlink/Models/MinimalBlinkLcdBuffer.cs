using CmosCpu.Computer.Devices;

namespace Symulator.Machines.MinimalBlink.Models;

public sealed class MinimalBlinkLcdBuffer
{
    public const int TotalWidth = 80;
    public const int TotalHeight = 14;

    private readonly bool[,] _pixels = new bool[TotalWidth, TotalHeight];

    public bool[,] Pixels => _pixels;

    public void RenderFrom(Hd44780Lcd lcd)
    {
        Array.Clear(_pixels, 0, _pixels.Length);

        for (int row = 0; row < 2; row++)
        {
            for (int col = 0; col < 16; col++)
            {
                int ddramAddr = row == 0 ? col : 0x40 + col;
                byte charCode = ddramAddr < lcd.Ddram.Length ? lcd.Ddram[ddramAddr] : (byte)0x20;
                RenderChar(charCode, col, row);
            }
        }
    }

    private void RenderChar(byte charCode, int col, int row)
    {
        int baseX = col * 5;
        int baseY = row * 7;

        byte[] pattern = Hd44780Cgrom.GetPattern(charCode);

        for (int py = 0; py < 7 && py < pattern.Length; py++)
        {
            byte rowBits = pattern[py];
            for (int px = 0; px < 5; px++)
            {
                int bx = baseX + px;
                int by = baseY + py;
                if (bx < TotalWidth && by < TotalHeight)
                    _pixels[bx, by] = (rowBits >> (4 - px) & 1) != 0;
            }
        }
    }
}

